void setLanguage(Language value) { current.store(value); }
Language language() { return current.load(); }

std::optional<Language> languageFromCode(std::string_view code) {
    std::string two;
    for (char c : code) {
        if (!std::isalpha(static_cast<unsigned char>(c))) break;
        two += char(std::tolower(static_cast<unsigned char>(c)));
    }
    if (two == "en" || two == "english" || two == "c" || two == "posix") return Language::english;
    if (two == "fr" || two == "french" || two == "fra" || two == "fre") return Language::french;
    if (two == "es" || two == "spanish" || two == "spa") return Language::spanish;
    return std::nullopt;
}

Language languageFromEnvironment() {
    for (const char* name : {"LC_ALL", "LC_MESSAGES", "LANG"})
        if (const char* value = std::getenv(name); value && *value)
            return languageFromCode(value).value_or(Language::english);   // the first one set decides, as in POSIX
    return Language::english;
}

std::string tr(std::string_view english) {
    const auto chosen = language();
    if (chosen != Language::english)
        if (const auto* entry = find(english)) {
            const auto text = chosen == Language::french ? entry->french : entry->spanish;
            if (!text.empty()) return std::string(text);
        }
    return std::string(english);
}

std::string trf(std::string_view english, std::initializer_list<std::string> arguments) {
    const std::string pattern = tr(english);
    std::string out;
    for (std::size_t i = 0; i < pattern.size(); ++i) {
        // {n} with a single digit; anything else is copied as written.
        if (pattern[i] == '{' && i + 2 < pattern.size() && std::isdigit(static_cast<unsigned char>(pattern[i + 1])) && pattern[i + 2] == '}') {
            const std::size_t index = std::size_t(pattern[i + 1] - '0');
            if (index < arguments.size()) {
                out += *(arguments.begin() + index);
                i += 2;
                continue;
            }
        }
        out += pattern[i];
    }
    return out;
}

